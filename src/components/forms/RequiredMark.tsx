/**
 * نشان «الزامی» کنار برچسب فیلد.
 *
 * دو چیز را با هم درست می‌کند:
 *
 * 1. رنگ. `--destructive` یک رنگ پرشدنی است (۶۰٪ روشنایی) و به‌عنوان متن،
 *    ۳.۷۸ می‌دهد — زیر ۴.۵. اما آن توکن پس‌زمینهٔ دکمهٔ حذف هم هست، پس
 *    عوض‌کردنش همه‌جا را تکان می‌دهد. red-700 محلی ۶.۴۷ روی کارت و ۵.۷۴
 *    روی `bg-muted` می‌دهد (red-600 روی دومی ۴.۲۸ است و رد می‌شود).
 *
 * 2. نام. این نشان داخل `<Label>` می‌نشیند، پس بدون `aria-hidden` نام
 *    فیلد برای screen reader می‌شود «نام حیوان ستاره» — و ستاره چیزی
 *    نمی‌گوید در حالی که `<input required>` خودش از قبل اعلامش می‌کند.
 */
export function RequiredMark() {
  return (
    <span aria-hidden className="text-red-700 dark:text-red-400">
      *
    </span>
  )
}
