# -*- coding: utf-8 -*-
"""
Self-host Vazirmatn as a VARIABLE font.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "public", "fonts")
CSS_PATH = os.path.join(FONTS, "vazirmatn.css")
URL = ("https://raw.githubusercontent.com/rastikerdar/vazirmatn/master/"
       "fonts/webfonts/Vazirmatn%5Bwght%5D.woff2")
LIC = ("https://raw.githubusercontent.com/rastikerdar/vazirmatn/master/"
       "OFL.txt")


def main():
    os.makedirs(FONTS, exist_ok=True)
    import urllib.request

    UA = {"User-Agent": "pawsmarket"}

    dest = os.path.join(FONTS, "Vazirmatn-var.woff2")
    skip = os.environ.get("SKIP_FONT_DOWNLOAD") == "1" and os.path.exists(dest)
    if skip:
        print(f"  keep existing {os.path.basename(dest)} "
              f"({os.path.getsize(dest) // 1024} KB)")
    else:
        for attempt in range(3):
            try:
                req = urllib.request.Request(URL, headers=UA)
                with urllib.request.urlopen(req, timeout=60) as r:
                    data = r.read()
                if len(data) < 10_000:
                    raise OSError(f"too small ({len(data)} B)")
                with open(dest, "wb") as f:
                    f.write(data)
                print(f"  downloaded Vazirmatn-var.woff2  "
                      f"{len(data) // 1024} KB")
                break
            except Exception as exc:          # noqa: BLE001
                if attempt == 2:
                    raise SystemExit(f"font download failed: {exc}")
                print(f"  retry ({attempt + 1})…")

    lic = os.path.join(FONTS, "OFL.txt")
    if not os.path.exists(lic):
        try:
            req = urllib.request.Request(LIC, headers=UA)
            with urllib.request.urlopen(req, timeout=60) as r:
                open(lic, "wb").write(r.read())
            print("  licence preserved: OFL.txt")
        except Exception as exc:              # noqa: BLE001
            print(f"  (licence fetch skipped: {exc})")

    css = """/* Self-hosted Vazirmatn VARIABLE font (SIL OFL 1.1).
   One file carries every weight 100-900 through its wght axis, so there is
   nothing to duplicate per weight and any intermediate weight a design asks
   for (350, 650...) renders for free.
   Regenerated by scripts/fetch_fonts.py — do not edit by hand. */
@font-face {
  font-family: 'Vazirmatn';
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url('Vazirmatn-var.woff2') format('woff2-variations');
}
"""
    open(CSS_PATH, "w", encoding="utf-8").write(css)
    print(f"  wrote {os.path.relpath(CSS_PATH, ROOT)}")

    # Remove the 12 per-weight files the first version wrote — they were two
    # unique files copied six times each, 430 KB of dead weight.
    removed = 0
    for f in os.listdir(FONTS):
        if f.endswith(".woff2") and f != "Vazirmatn-var.woff2":
            os.remove(os.path.join(FONTS, f))
            removed += 1
    print(f"  removed {removed} per-weight duplicate file(s)")


if __name__ == "__main__":
    main()