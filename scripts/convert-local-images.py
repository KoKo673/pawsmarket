"""Generate webp variants for the bundled images under public/images.

Why a script and not a one-off: the set grows (scripts/fetch_store_images.py,
enrich_digikala.py) and a hand-converted tree drifts back to JPEG as soon as
someone adds a file. Running this again is the whole maintenance story.

What it emits, per source JPEG `foo.jpg`:

    foo.jpg          kept, untouched — the fallback and the deep-zoom original
    foo.w660.webp    ~2x a 335px card
    foo.w1024.webp   ~2x a 529px hero at DESKTOP (413-529 CSS px)

Widths come from measurement (scripts/measure-image-needs.py):
  - the widest local-image box on any page is the home hero at 529 CSS px
  - explore cards are 335-413 CSS px
So 660 covers every card at 2x, and 1024 is the only rung that can feed a
retina desktop hero. Most sources are narrower than 1024, so that variant is
skipped — upscaling would spend bytes to add no detail.

The never-grow rule: a variant is only written if it is smaller than the
source. Measured on a 30-file sample per directory, webp came out *larger*
for roughly one file in thirty (cat-grey.jpg: 110 KB -> 110 KB). Serving a
bigger file to claim "optimised" is worse than serving the original.

Idempotent: a variant is skipped when it exists and is newer than its source.
"""
import argparse
import io
import pathlib
import sys

from PIL import Image

REPO = pathlib.Path(__file__).resolve().parent.parent
IMG = REPO / "public" / "images"

WIDTHS = (660, 1024)
QUALITY = 82


def variant_path(src: pathlib.Path, width: int) -> pathlib.Path:
    return src.with_name(f"{src.stem}.w{width}.webp")


def encode(src: pathlib.Path, width: int) -> bytes | None:
    im = Image.open(src)
    if im.width <= width * 0.98:
        # Never upscale: the source cannot fill this rung.
        return None
    im = im.resize((width, round(width * im.height / im.width)), Image.LANCZOS)
    buf = io.BytesIO()
    im.convert("RGB").save(buf, "WEBP", quality=QUALITY, method=6)
    return buf.getvalue()


MANIFEST = REPO / "src" / "lib" / "local-image-variants.ts"


def write_manifest() -> int:
    """Record which rungs exist, so the frontend never invents a URL.

    The alternative — inferring from the source width in the browser — needs
    the natural size of every image before building a srcset, which is a
    round trip per tile. A generated map is one import and cannot disagree
    with the files, because it is rebuilt from them on every run.
    """
    entries: dict[str, list[int]] = {}
    for v in sorted(IMG.rglob("*.webp")):
        stem, _, w = v.stem.rpartition(".w")
        if not w.isdigit():
            continue
        url = "/" + v.with_suffix("").relative_to(REPO / "public").as_posix()
        # strip the .wNNN suffix back off to get the original's stem
        url = url[: -len(f".w{w}")] + ".jpg"
        entries.setdefault(url, []).append(int(w))
    # A source whose original is not on disk is an orphan variant.
    entries = {k: sorted(v) for k, v in entries.items()
               if (REPO / "public" / k.lstrip("/")).exists()}
    lines = [
        "// GENERATED by scripts/convert-local-images.py — do not edit.",
        "//",
        "// Which webp rungs exist for each bundled image. The converter refuses",
        "// to upscale, so a 820px source has 660 but no 1024 — and a srcset",
        "// naming a missing file renders a broken tile on a retina desktop.",
        "// The frontend reads this instead of guessing.",
        "export const LOCAL_IMAGE_VARIANTS: Record<string, readonly number[]> = {",
    ]
    for url in sorted(entries):
        ws = ", ".join(str(w) for w in entries[url])
        lines.append(f"  {url!r}: [{ws}],".replace("'", "'"))
    lines.append("}")
    lines.append("")
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"manifest       {MANIFEST.relative_to(REPO)} ({len(entries)} images)")
    return len(entries)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=0,
                    help="stop after N source files (for a timed trial)")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--no-manifest", action="store_true")
    args = ap.parse_args()

    written = skipped_small = skipped_uptodate = not_smaller = 0
    bytes_in = bytes_out = 0
    start = pathlib.Path.cwd()

    sources = sorted(p for p in IMG.rglob("*.jpg") if p.is_file())
    if args.limit:
        sources = sources[: args.limit]

    for i, src in enumerate(sources, 1):
        if i % 100 == 0:
            print(f"  {i}/{len(sources)}  written={written} not_smaller={not_smaller}",
                  file=sys.stderr, flush=True)
        for width in WIDTHS:
            dst = variant_path(src, width)
            if dst.exists() and dst.stat().st_mtime >= src.stat().st_mtime:
                skipped_uptodate += 1
                continue
            try:
                data = encode(src, width)
            except Exception as exc:  # noqa: BLE001 — report and keep going
                print(f"  ERROR {src}: {exc}", file=sys.stderr)
                continue
            if data is None:
                skipped_small += 1
                continue
            if len(data) >= src.stat().st_size:
                not_smaller += 1
                continue
            if not args.dry_run:
                dst.write_bytes(data)
            written += 1
            bytes_in += src.stat().st_size
            bytes_out += len(data)

    if not args.no_manifest:
        write_manifest()

    print(f"\nsources        {len(sources)}")
    print(f"written        {written}"
          + (" (dry run)" if args.dry_run else ""))
    print(f"skipped, source narrower than rung   {skipped_small}")
    print(f"skipped, webp not smaller            {not_smaller}")
    print(f"skipped, already up to date          {skipped_uptodate}")
    if written:
        print(f"bytes  {bytes_in/1e6:.1f} MB source -> {bytes_out/1e6:.1f} MB (variants)")
    return 0


if __name__ == "__main__":
    sys.exit(main())