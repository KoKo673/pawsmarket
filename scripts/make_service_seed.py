"""Emit the remap + service-centre seed as one SQL transaction.

Two things happen here and they must both land or neither:

  1. Every existing store moves to id 10000+ so the catalogue ids stop
     colliding with real businesses. products.store_id and
     bookings.store_id follow, because they point at those rows.

  2. The 351 service centres from catalog.json are inserted at their
     catalogue ids. Those ids are what /booking/:storeId already puts in
     the URL, so after this the catalogue and the API finally agree.

Shops and products are deliberately excluded: voice notes 04-06 put the
product marketplace on a separate footing that has not been designed yet.

Rows are written as one INSERT ... VALUES with a parameter-free literal
body so the script can be piped straight into psql. Values are escaped,
not interpolated - the catalogue holds apostrophes in business names.

Usage:
    python scripts/make_service_seed.py /tmp/service-seed.sql
"""

import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG = os.path.join(HERE, "..", "public", "catalog.json")

SERVICE = {"vet", "groomer", "boarding", "shelter"}
SHIFT = 10_000


def lit(s):
    """A single-quoted SQL string literal."""
    return "'" + str(s).replace("'", "''") + "'"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)

    with open(CATALOG, encoding="utf-8") as fh:
        catalog = json.load(fh)

    stores = [s for s in catalog["stores"] if s["category"] in SERVICE]
    if not stores:
        sys.exit("catalog has no service centres - wrong file?")

    # Guard: the shift must not collide with a catalogue id.
    top = max(s["id"] for s in catalog["stores"])
    if SHIFT <= top:
        sys.exit(f"SHIFT={SHIFT} would collide with catalogue id {top}")
    if any(s["id"] >= SHIFT for s in stores):
        sys.exit("a service centre already sits above the shift")

    out = io.open(sys.argv[1], "w", encoding="utf-8", newline="\n")
    w = out.write

    w("-- generated by scripts/make_service_seed.py - do not hand-edit\n")
    w(f"-- {len(stores)} service centres, existing stores shift +{SHIFT}\n")
    w("BEGIN;\n\n")

    w("-- 1. which rows move, and where to\n")
    w("CREATE TEMP TABLE store_remap ON COMMIT DROP AS\n")
    w(f"  SELECT id AS old_id, id + {SHIFT} AS new_id FROM stores;\n\n")

    # bookings.store_id is a foreign key with no ON UPDATE, so it blocks the
    # parent's id from moving in BOTH orders: update the parent first and the
    # child dangles, update the child first and the parent is still referenced.
    # Rebuilding the constraint with ON UPDATE CASCADE is the only order-free
    # way, and it is also the right end state - moving a store's id should
    # carry its bookings with it, not silently orphan them.
    w("-- 2. rebuild the booking FK so a moved store carries its rows.\n")
    w("--    Migrations/0005 created it without ON UPDATE; this makes the\n")
    w("--    cascade explicit rather than working around it.\n")
    w("ALTER TABLE bookings DROP CONSTRAINT bookings_store_id_fkey;\n")
    w("ALTER TABLE bookings ADD CONSTRAINT bookings_store_id_fkey\n")
    w("  FOREIGN KEY (store_id) REFERENCES stores(id)\n")
    w("  ON DELETE CASCADE ON UPDATE CASCADE;\n\n")

    w("-- 3. move the stores. One statement, so a duplicate id aborts the\n")
    w("--    transaction rather than half-applying. Bookings follow.\n")
    w("UPDATE stores s SET id = r.new_id FROM store_remap r WHERE s.id = r.old_id;\n\n")

    w("-- 4. products carry no FK at all, so they are updated explicitly.\n")
    w("UPDATE products p SET store_id = r.new_id\n")
    w("  FROM store_remap r WHERE p.store_id = r.old_id;\n\n")

    w("-- 5. service centres at their catalogue ids\n")
    w("INSERT INTO stores (id, name, address, category, location, created_at) VALUES\n")
    rows = []
    for s in stores:
        rows.append(
            "  (%d, %s, %s, %s, "
            "ST_SetSRID(ST_MakePoint(%s, %s), 4326), now())"
            % (s["id"], lit(s["name"]), lit(s["address"]), lit(s["category"]),
               repr(float(s["lng"])), repr(float(s["lat"])))
        )
    w(",\n".join(rows))
    w(";\n\n")

    w("-- 6. sequences past both ranges, or the next insert collides\n")
    w("SELECT setval('stores_id_seq',   (SELECT max(id) FROM stores));\n")
    w("SELECT setval('products_id_seq', (SELECT max(id) FROM products));\n\n")

    w("COMMIT;\n")
    out.close()


if __name__ == "__main__":
    main()
